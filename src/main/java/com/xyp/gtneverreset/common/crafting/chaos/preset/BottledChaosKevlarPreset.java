/** Independent precursor preparations followed by polymer synthesis through the final Kevlar plate. */
public final class BottledChaosKevlarPreset {

    public static void registerRecipeChains(BottledChaosRecipeCatalog catalog) {
        // spotless:off
        // Finishing: retain all precursors as inputs; combine both polymer syntheses through the final plate.
        var kevlar = catalog.registerChain("kevlar", 64, TierEU.RECIPE_UV, ParaphenylenediamineDust,
            new Object[] { KevlarPlate }, new Object[] {},
            catalog.markRecipe(LargeChemicalReactor, new Object[] { ParaphenylenediamineDust, TerephthaloylChlorideDust }, LiquidCrystalKevlar, 1),
            catalog.markRecipe(FluidSolidifier, LiquidCrystalKevlar, KevlarFiber, -1),
            catalog.markRecipe(Assembler, KevlarFiber, WovenKevlar, 8),
            catalog.markRecipe(ChemicalBath, new Object[] { WovenKevlar, PolyurethaneResin }, KevlarPlate, -1));
        kevlar.hideInputMarker();
        kevlar.includeSynthesisStep(LargeChemicalReactor, PolyurethaneResin,
            new Object[] { KevlarCatalystDust, PentaerythritolDust, DiphenylmethaneDiisocyanateDust, EthyleneGlycol, SiliconeOil }, 1);

        // Liquid-crystal precursors: diamine, acid chloride, solvent, then algae-derived calcium chloride.
        var paraphenylenediamine = catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, Benzene,
            new Object[] { ParaphenylenediamineDust }, new Object[] { ParaphenylenediamineDust },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { Nitroaniline, PalladiumDust, NitrogenDioxideGas }, ParaphenylenediamineDust, 1));
        paraphenylenediamine.hideInputMarker();
        paraphenylenediamine.includeSynthesisStep(LargeChemicalReactor,
            Nitrobenzene, new Object[] { Benzene, SulfuricAcid, NitricAcid, DistilledWater }, 1);

        catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, Benzene,
            new Object[] { TerephthaloylChlorideDust }, new Object[] { TerephthaloylChlorideDust },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { ThionylChloride, DimethylTerephthalate, CarbonDioxideGas }, TerephthaloylChlorideDust, 1)).hideInputMarker();
        catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, CarbonDust,
            new Object[] { NMethylpyrrolidone }, new Object[] { NMethylpyrrolidone },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { MethylamineGas, GammaButyrolactone }, NMethylpyrrolidone, -1)).hideInputMarker();
        var calciumChloride = catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, RedAlgaeBiomass,
            new Object[] { CalciumChlorideDust }, new Object[] { CalciumChlorideDust },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { CalciumCarbonateDust, HydrochloricAcid }, CalciumChlorideDust, 8));
        calciumChloride.hideInputMarker();
        calciumChloride.includeSynthesisStep(Extractor, CalciumCarbonateDust, RedCelluloseFiber, -1);

        // Resin precursors: use algae-derived butanol for the catalyst, then prepare the four other feeds.
        var kevlarCatalyst = catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, TinDust,
            new Object[] { KevlarCatalystDust }, new Object[] { KevlarCatalystDust },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { TinDust, Butanol, PropionicAcid, IronIIIChloride }, KevlarCatalystDust, 1));
        kevlarCatalyst.hideInputMarker();
        kevlarCatalyst.includeSynthesisStep(ChemicalPlant, Butanol,
            new Object[] { GoldenBrownCelluloseFiber, RedCelluloseFiber, FermentationBase }, 5);

        catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, SodiumDust,
            new Object[] { PentaerythritolDust }, new Object[] { PentaerythritolDust },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { SodiumHydroxideDust, Formaldehyde, AcetaldehydeGas }, PentaerythritolDust, -1)).hideInputMarker();
        var diphenylmethaneDiisocyanate = catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, Benzene,
            new Object[] { DiphenylmethaneDiisocyanateDust }, new Object[] { DiphenylmethaneDiisocyanateDust },
            catalog.markRecipe(DistillationTower, DiphenylmethaneDiisocyanateMixture, DiphenylmethaneDiisocyanateDust, -1));
        diphenylmethaneDiisocyanate.hideInputMarker();
        diphenylmethaneDiisocyanate.includeSynthesisStep(LargeChemicalReactor,
            Nitrobenzene, new Object[] { Benzene, SulfuricAcid, NitricAcid, DistilledWater }, 1);
        var ethyleneGlycol = catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, EthyleneGas,
            new Object[] { EthyleneGlycol }, new Object[] { EthyleneGlycol },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { EthyleneOxideGas, Water }, EthyleneGlycol, 1));
        ethyleneGlycol.hideInputMarker();
        ethyleneGlycol.requireCircuit(1);
        var siliconeOil = catalog.registerAlternativeChain("kevlar", TierEU.RECIPE_UV, SiliconDust,
            new Object[] { SiliconeOil }, new Object[] { SiliconeOil },
            catalog.markRecipe(LargeChemicalReactor, new Object[] { EthyleneOxideGas, Dimethyldichlorosilane, Water }, SiliconeOil, 2));
        siliconeOil.hideInputMarker();
        siliconeOil.requireCircuit(2);
        catalog.orderDisplayRecipes("kevlar", Benzene, CarbonDust, RedAlgaeBiomass, TinDust, SodiumDust,
            EthyleneGas, SiliconDust, ParaphenylenediamineDust);

        // Shared upstream paths stop at the registered precursor outputs, keeping the finishing stage separate.
        catalog.includeSynthesisStep(Assembler, GoldenBrownCelluloseFiber, GoldenBrownAlgaeBiomass, -1);
        catalog.includeSynthesisStep(Assembler, RedCelluloseFiber, RedAlgaeBiomass, -1);

        // Monomer input branch: aniline nitration -> diamine; dilute acids return before final reagent expansion.
        catalog.includeSynthesisStep(LargeChemicalReactor, Nitroaniline,
            new Object[] { Aniline, AceticAnhydride, NitrationMixture }, 2);
        catalog.includeSynthesisStep(LargeChemicalReactor, Aniline, new Object[] { Nitrobenzene, PalladiumDust }, 1);
        catalog.includeSynthesisStep(ChemicalDehydratorNonCell, AceticAnhydride, AceticAcid, -1);
        catalog.includeSynthesisStep(MixerNonCell, NitrationMixture, new Object[] { NitricAcid, SulfuricAcid }, 1);

        // Solvent input branch: acetylene + formaldehyde -> butynediol -> butanediol -> lactone -> NMP.
        catalog.includeSynthesisStep(LargeChemicalReactor, GammaButyrolactone, new Object[] { Butanediol, CopperDust }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, Butanediol, new Object[] { ButynediolDust, ActivatedRaneyNickelDust }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, ButynediolDust,
            new Object[] { CopperIIOxideDust, BismuthIIIOxideDust, SiliconDioxideDust, AcetyleneGas, Formaldehyde }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, CopperIIOxideDust, new Object[] { CopperDust, OxygenGas }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, BismuthIIIOxideDust, new Object[] { BismuthDust, OxygenGas }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, AcetyleneGas, new Object[] { CalciumCarbideDust, Water }, 1);
        catalog.includeSynthesisStep(BlastFurnace, CalciumCarbideDust, new Object[] { QuicklimeDust, CarbonDust }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, MethylamineGas,
            new Object[] { AluminiumOxideDust, SiliconDioxideDust, Methanol, AmmoniaGas }, 10);
        catalog.includeSynthesisStep(ChemicalPlant, Formaldehyde, new Object[] { Methanol, OxygenGas, FormaldehydeCatalyst }, 21);
        catalog.includeSynthesisStep(LargeChemicalReactor, ActivatedRaneyNickelDust,
            new Object[] { NickelAluminideIngot, SodiumHydroxideDust, Water }, -1);
        catalog.includeSynthesisStep(BlastFurnace, NickelAluminideIngot, new Object[] { NickelDust, AluminiumDust }, -1);

        // Acid-chloride input branch: paraxylene -> terephthalic acid -> dimethyl ester -> acid chloride.
        catalog.includeSynthesisStep(LargeChemicalReactor, DimethylTerephthalate,
            new Object[] { TerephthalicAcid, Methanol, SulfuricAcid }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, TerephthalicAcid,
            new Object[] { Paraxylene, CobaltNaphthenateDust, OxygenGas }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, Paraxylene, new Object[] { Benzene, MethaneGas }, 3);
        catalog.includeSynthesisStep(LargeChemicalReactor, CobaltNaphthenateDust,
            new Object[] { CobaltHydroxideDust, NaphthenicAcid }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, CobaltHydroxideDust,
            new Object[] { CobaltNitrateDust, PotassiumHydroxideDust }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, CobaltNitrateDust, new Object[] { CobaltDust, NitricAcid }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, PotassiumHydroxideDust, new Object[] { PotassiumDust, Water }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, ThionylChloride,
            new Object[] { SulfurTrioxideGas, SulfurDichloride }, -1);
        catalog.includeSynthesisStep(LargeChemicalReactor, SulfurDichloride, new Object[] { SulfurDust, ChlorineGas }, 2);
        catalog.includeSynthesisStep(LargeChemicalReactor, SulfurTrioxideGas, new Object[] { SulfurDioxideGas, OxygenGas }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, SulfurDioxideGas, new Object[] { SulfurDust, OxygenGas }, 3);

        // Resin input branches: diamino mixture -> diisocyanate; polyol, silicone oil and catalyst synthesis.
        catalog.includeSynthesisStep(LargeChemicalReactor, DiphenylmethaneDiisocyanateMixture,
            new Object[] { DiaminodiphenylmethaneMixture, Phosgene }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, DiaminodiphenylmethaneMixture,
            new Object[] { Formaldehyde, Aniline, HydrochloricAcid }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, Phosgene, new Object[] { CarbonMonoxideGas, ChlorineGas }, 2);
        catalog.includeSynthesisStep(LargeChemicalReactor, EthyleneOxideGas,
            new Object[] { EthyleneGas, OxygenGas, SilverDust, AluminiumOxideDust }, 2);
        catalog.includeSynthesisStep(LargeChemicalReactor, Dimethyldichlorosilane, new Object[] { SiliconDust, ChloromethaneGas }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, AcetaldehydeGas, new Object[] { EthyleneGas, OxygenGas }, 5);
        catalog.includeSynthesisStep(LargeChemicalReactor, PropionicAcid,
            new Object[] { EthyleneGas, CarbonMonoxideGas, NickelTetracarbonyl, Water }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, IronIIIChloride, new Object[] { IronDust, HydrochloricAcid }, -1);

        // Final reagent boundaries and native dilute-acid recovery; do not discard other coproducts.
        catalog.includeSynthesisPath(QuicklimeDust, SodiumHydroxideDust, AceticAcid, AmmoniaGas,
            NickelTetracarbonyl, MethaneGas, Methanol, CarbonMonoxideGas, CarbonDioxideGas);
        catalog.includeDecompositionPath(SodiumMethoxideDust);
        catalog.includeSynthesisStep(LargeChemicalReactor, NitrogenDioxideGas, new Object[] { NitrogenMonoxideGas, OxygenGas }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, NitrogenMonoxideGas, new Object[] { AmmoniaGas, OxygenGas }, 1);
        catalog.includeSynthesisStep(LargeChemicalReactor, ChloromethaneGas, new Object[] { Methanol, HydrochloricAcid }, 2);
        catalog.includeDecompositionStep(DistillationTower, DilutedHydrochloricAcid, HydrochloricAcid, -1);
        catalog.registerDeferredReagents(Nitrobenzene, AceticAcid, Methanol, SodiumHydroxideDust,
            CarbonMonoxideGas, CarbonDioxideGas, SulfurDioxideGas);
        // spotless:on
    }
}
